"""
لایه‌ی استخراج: متن خام پیام تلگرام -> JSON ساختاریافته.
"""
import json
import logging
from .llm_pool import call_with_fallback

logger = logging.getLogger("extractor")

EXTRACTION_SYSTEM_PROMPT = """
تو یک استخراج‌کننده‌ی داده از آگهی‌های خریدوفروش خودرو در کانال‌های تلگرام هستی.
متن پیام معمولاً اسلنگ، ایموجی تزئینی، امضای کانال (مثل @channel_name یا «کانال ما») و فرمت نامرتب دارد.
آگهی‌ها فرمت یکسانی ندارند — بعضی خط‌به‌خط با لیبل (مثل 🏷️ مدل: / 💰 قیمت:) نوشته می‌شوند، بعضی یک پاراگراف فشرده‌ی پر از ایموجی.

فقط یک JSON معتبر با دقیقاً این ساختار برگردان، بدون هیچ توضیح اضافه قبل یا بعدش و بدون بلاک کد:

{
  "is_ad": true یا false,
  "ad_type": "for_sale" یا "wanted_to_buy" یا null,
  "car_name": رشته یا null,
  "trim": رشته یا null,
  "color": رشته یا null,
  "production_year": رشته یا null,
  "mileage_km": عدد یا null,
  "city": رشته یا null,
  "delivery_unit": "month" یا "day" یا null,
  "delivery_status": رشته یا null,
  "phone": رشته یا null,
  "price_amount": عدد یا null,
  "price_label": رشته یا null,
  "notes": رشته یا null
}

توضیح فیلدها:
- is_ad: آیا این پیام درباره‌ی یک خودروی خاص با تماس است؟ (هم آگهی فروش هم درخواست خرید را true بگذار)
- ad_type: کلماتی مثل «خریدارم» یعنی wanted_to_buy. اگر فروشنده‌ست for_sale.
- production_year — قانون قطعی برای سال‌های مخفف: اعداد سه‌رقمی مثل "404"، "405"، "402" که در کنار مدل خودرو
  آمده‌اند (نه قیمت، نه کارکرد) معمولاً مخفف سال شمسی هستند با حذف رقم اول «۱». همیشه به فرم کامل چهاررقمی برگردان:
  "405" -> "1405"   |   "404/405" -> "1404/1405"   |   "1403" -> "1403" (already full, keep as is)
- city: اگر اسم یک شهر ایرانی (مثل تهران، قم، کرمانشاه، اصفهان، مشهد، تبریز و...) به‌صورت جدا یا کنار کلمه‌ی
  «پلاک» آمده، اینجا بگذار. اگر فقط «پلاک تهران» بود ولی شهر دیگری در متن مشخص نبود، همان را city بگذار.
- delivery_unit — اصطلاح رایج این کانال‌ها برای پیش‌فروش/تحویل:
  "برج روز" یا چیزی شبیه آن یعنی تحویل سریع (در حد چند روز) -> delivery_unit: "day"
  "برج ماه" یا "برج به ماه" یعنی تحویل کندتر/پیش‌فروش (چند ماهه) -> delivery_unit: "month"
  اگر چنین عبارتی در متن نبود، null بگذار.
- mileage_km: کلمات «کارکرد»، «آمپر»، و «N تا کار» همگی به معنای کارکردند.
  اگر عدد کوچک بود (زیر چند صد) و همراه «تا کار» بود، احتمالاً منظور هزار کیلومتره (مثلا «۴۰ تا کار» = 40000).
  اگر مطمئن نیستی، عدد را همانطور که نوشته شده بگذار و ابهام را در notes بنویس.
- phone: فقط اولین شماره؛ اگر چند شماره بود بقیه را در notes بنویس.
- price_amount — قانون قطعی (روی این مردد نباش، وقت زیادی صرف فکرکردن دربارهٔ واحدش نکن):
  در این کانال‌ها قیمت تقریباً همیشه به «میلیون تومان» نوشته می‌شود بدون ذکر واحد.
  پس عدد نوشته‌شده را (بعد از پاک‌کردن جداکننده مثل ویرگول/نقطه/اسلش و تبدیل رقم به لاتین) در 1000000 ضرب کن
  و عدد کامل تومان را به‌عنوان price_amount بگذار:
  "2100" -> 2100000000   |   "۱۶،۲۵۰" -> 16250000000   |   "۳,۶۵۰" -> 3650000000   |   "۲/۳۸۰" -> 2380000000   |   "1/950" -> 1950000000   |   "2645💎" -> 2645000000
  اگر واقعاً هیچ رقمی در متن نبود (فقط ایموجی یا کلمه)، price_amount را null بگذار.
- price_label: مثلا "خوش قیمت"، "کف قیمت ایران"، "بیا رو خط ببند"، یا "تماس بگیرید برای قیمت ویژه"
  (وقتی فقط ایموجی آتش 🔥 کنار کلمه‌ی «قیمت» بدون رقم آمده، یعنی قیمت خاص دارد و باید تماس گرفت — نه که قیمت ندارد).
- notes: هر بخش مهمی که در فیلدهای بالا جا نشد (چند قیمت/رنگ، چند شماره، ابهام واحد کارکرد و...).
  امضای کانال، اسم فروشنده، یا تگ @ را اینجا هم نیار، مگر لازم باشد.
- car_name: نام مدل را به فارسی بنویس اگر متن اصلی فارسی بود (مثلا "کیا اپتیما" نه "Kia Optima")، مگر خودِ متن از حروف لاتین استفاده کرده باشد.

نکات کلی:
- همه‌ی ارقام خروجی باید با رقم لاتین (0-9) باشند، نه فارسی/عربی.
- اگر مطمئن نیستی یک فیلد چه مقداری دارد، آن را null بگذار — حدس اشتباه نزن.
- توضیحات داخل notes را به فارسی بنویس، نه انگلیسی یا زبان دیگر.
- در فکرکردن خودت کوتاه و مستقیم باش؛ روی قوانین قطعی بالا تردید نکن، همان‌ها را اعمال کن و سریع به نتیجه برس.
"""


def _clean_json_text(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        text = text.strip("`")
        if text.startswith("json"):
            text = text[4:]
    return text.strip()


def extract_car_ad(message_text: str, max_attempts: int = 2) -> dict:
    messages = [
        {"role": "system", "content": EXTRACTION_SYSTEM_PROMPT},
        {"role": "user", "content": message_text},
    ]

    last_error = None
    for attempt in range(1, max_attempts + 1):
        raw_content, used_provider = call_with_fallback(messages)
        try:
            parsed = json.loads(_clean_json_text(raw_content))
            parsed["_provider_used"] = used_provider
            return parsed
        except json.JSONDecodeError as e:
            last_error = e
            logger.warning(
                f"⚠️ پاسخ JSON معتبر نبود (تلاش {attempt}/{max_attempts}): {raw_content[:200]!r}"
            )

    raise ValueError(f"بعد از {max_attempts} تلاش، پاسخ معتبر JSON نگرفتیم. آخرین خطا: {last_error}")